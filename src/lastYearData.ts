const grouped = new Map<string, string[]>();
for (const row of rows.split("\n")) {
  const [seat, name] = row.split("|");
  grouped.set(name, [...(grouped.get(name) || []), seat]);
}

export const TASHפו_USERS: LastYearImport[] = [...grouped.entries()].map(([fullName, seats], index) => {
  const [firstName, ...lastName] = fullName.split(/\s+/);
  // In the supplied list a one-word entry is a family name. Keeping it in the
  // family-name field lets a new form entry such as "דוד כהן" match "כהן".
  return lastName.length === 0
    ? { id: `tashפו-${index + 1}`, firstName: "", lastName: firstName, seats }
    : { id: `tashפו-${index + 1}`, firstName, lastName: lastName.join(" "), seats };
});
